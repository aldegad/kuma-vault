#!/usr/bin/env node
// Generate src/server/unicode-tables.mjs from two files of the Unicode Character Database:
//
//   node scripts/server/gen-unicode-tables.mjs <CaseFolding.txt> <DerivedAge.txt>
//
// Both must be of UNICODE_VERSION (https://www.unicode.org/Public/<version>/ucd/). That is the
// Unicode version the macOS clients' APFS knows (docs/server.md, "What a checkout can write"):
// APFS refuses a name with a code point it does not know, so the receive rules accept only
// code points assigned by that version. Raise it only after every client Mac takes the new
// code points; the generated file is checked in and never fetched at run time.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const UNICODE_VERSION = "16.0.0";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "server", "unicode-tables.mjs");

const [caseFoldingPath, derivedAgePath] = process.argv.slice(2);
if (!caseFoldingPath || !derivedAgePath) {
  process.stderr.write("usage: gen-unicode-tables.mjs <CaseFolding.txt> <DerivedAge.txt>\n");
  process.exit(2);
}

function readUcd(path) {
  const text = readFileSync(path, "utf8");
  const header = text.split("\n", 1)[0];
  if (!header.includes(`-${UNICODE_VERSION}.txt`)) throw new Error(`${path} is not of Unicode ${UNICODE_VERSION}: ${header}`);
  return text;
}

const isNoncharacter = (cp) => (cp >= 0xfdd0 && cp <= 0xfdef) || (cp & 0xfffe) === 0xfffe;
const isSurrogate = (cp) => cp >= 0xd800 && cp <= 0xdfff;

// Assigned code points: every code point DerivedAge lists (it lists assigned ones only), less
// surrogates (never in valid UTF-8) and noncharacters (APFS refuses them although they are listed).
const assigned = new Uint8Array(0x110000);
for (const line of readUcd(derivedAgePath).split("\n")) {
  const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;/);
  if (!m) continue;
  for (let cp = parseInt(m[1], 16), hi = parseInt(m[2] ?? m[1], 16); cp <= hi; cp += 1) {
    if (!isSurrogate(cp) && !isNoncharacter(cp)) assigned[cp] = 1;
  }
}
const ranges = [];
for (let cp = 0; cp < 0x110000; cp += 1) {
  if (!assigned[cp]) continue;
  const lo = cp;
  while (cp + 1 < 0x110000 && assigned[cp + 1]) cp += 1;
  ranges.push(lo === cp ? lo.toString(16) : `${lo.toString(16)}-${cp.toString(16)}`);
}

// Full case folding: statuses C (common) and F (full). S is the simple alternative to F and
// T the Turkic one; APFS folds neither (dotless i stays apart from i).
const folds = [];
for (const line of readUcd(caseFoldingPath).split("\n")) {
  const m = line.match(/^([0-9A-F]+); ([CF]); ([0-9A-F ]+);/);
  if (!m) continue;
  folds.push(`${m[1].toLowerCase()}:${m[3].trim().toLowerCase().replaceAll(" ", ".")}`);
}

function wrap(items, sep) {
  const lines = [];
  let line = "";
  for (const item of items) {
    if (line && line.length + item.length + 1 > 96) {
      lines.push(line);
      line = "";
    }
    line += `${item}${sep}`;
  }
  if (line) lines.push(line);
  return lines.map((l) => `  "${l}"`).join(" +\n");
}

writeFileSync(
  OUT,
  `// Generated by scripts/server/gen-unicode-tables.mjs from the Unicode ${UNICODE_VERSION} CaseFolding.txt and
// DerivedAge.txt. Do not edit; regenerate. Read by checkout-paths.mjs.

export const UNICODE_VERSION = "${UNICODE_VERSION}";

/** Assigned code points less surrogates and noncharacters: hex \`lo-hi\` or \`cp\`, comma-separated. */
export const ASSIGNED_RANGES =
${wrap(ranges, ",")};

/** Full case folding (CaseFolding C + F): hex \`cp:fold\`, a multi-code-point fold dot-separated. */
export const CASE_FOLDS =
${wrap(folds, ",")};
`,
);
process.stdout.write(`${OUT}: ${ranges.length} assigned ranges, ${folds.length} folds (Unicode ${UNICODE_VERSION})\n`);
